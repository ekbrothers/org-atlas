// Generates the Org Atlas authoring agent from the vocabulary files and the
// JSON Schema, so the agent always describes exactly what the engine accepts.
//
// Outputs (written by `npm run agent`, checked in CI):
//   agent/org-atlas-agent.md            portable system prompt for any LLM
//   agent/tool.json                     tool / function definition (structured output)
//   .claude/agents/org-atlas-author.md  Claude Code subagent
//   AGENTS.md                           instructions for coding agents in this repo

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './config.mjs';
import { ENTITY_KINDS, KIND_ALIASES, loadVocab } from './model.mjs';
import { buildSchema } from './schema.mjs';

// Kinds whose files accept inline relationship fields.
const INLINE_KINDS = ['platform', 'product', 'committee'];

const GENERATED = 'Generated by `npm run agent` from engine/vocab/*.yaml and the JSON Schema. Do not edit by hand.';

const table = (head, rows) =>
  [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map((c) => String(c ?? '').replace(/\|/g, '/')).join(' | ')} |`)].join('\n');
const ids = (list) => list.map((x) => `\`${x.id}\``).join(', ');

// Field documentation for each kind, read from the schema itself.
function kindFields(schema, kind) {
  const def = schema.definitions[kind];
  const required = new Set(def.required ?? []);
  return Object.entries(def.properties)
    .filter(([k]) => !['kind', 'description', 'order', 'tags', 'links', 'meta'].includes(k))
    .map(([k, v]) => {
      let type = v.enum ? v.enum.map((x) => `\`${x}\``).join(', ') : v.type ?? (v.anyOf ? 'reference(s)' : '');
      if (k === 'members') type = 'list of person ids or { person, role, representing }';
      if (k === 'memberships') type = 'list of team ids or { team, primary, role }';
      const desc = k === 'id' ? 'Stable, unique per kind.' : k === 'name' ? 'Display name.' : v.description;
      return `\`${k}\`${required.has(k) ? ' (required)' : ''}: ${type}${desc ? `. ${desc}` : ''}`;
    });
}

export function buildAgent() {
  const vocab = loadVocab();
  const schema = buildSchema(vocab);
  const example = readFileSync(join(ROOT, 'examples/bundle/data/atlas.json'), 'utf8').trim();
  const aliases = Object.entries(KIND_ALIASES)
    .filter(([, v]) => ENTITY_KINDS.includes(v))
    .map(([k, v]) => `\`${k}\` = \`${v}\``)
    .join(', ');
  const rels = vocab.relTypes.filter((t) => !t.structural);
  const structural = vocab.relTypes.filter((t) => t.structural);

  const relRows = rels.map((t) => [
    `\`${t.id}\``,
    t.category,
    t.from.join(', '),
    t.to.join(', '),
    t.description,
    [t.inline && `\`${t.inline}:\` on the ${t.to.join('/')}`, t['inline-on-source'] && `\`${t['inline-on-source']}:\` on the ${t.from.filter((k) => INLINE_KINDS.includes(k)).join('/')}`].filter(Boolean).join('; '),
    (t.attributes ?? []).join(', '),
    (t.aliases ?? []).join(', '),
  ]);

  const kindSections = ENTITY_KINDS.map((k) => `### \`${k}\`\n\n${kindFields(schema, k).map((f) => `- ${f}`).join('\n')}`).join('\n\n');

  const body = `# Org Atlas authoring agent

<!-- ${GENERATED} -->

You are the **Org Atlas authoring agent**. You turn descriptions of an organization (business units, teams, people, platforms, products, committees and how they relate) into data that Org Atlas renders as org charts, team pages, platform and product ownership maps, committee pages and relationship maps.

You can create a whole new chart, add to an existing one, or change relationships. You only ever produce data; the site draws the diagrams.

## How you work

1. **Understand the request.** If key facts are missing (who owns a platform, which business unit a team is in), ask briefly, or make the smallest reasonable assumption and list it after the output. Never invent real people's names: if names are not given, use role-based placeholders ("Data Engineer 1") or model the seat as a vacancy.
2. **Produce one JSON bundle** (format below). When changing an existing bundle, return the complete updated bundle, keeping every existing id stable.
3. **Validate.** If you can run commands, save the bundle as \`data/atlas.json\` and run \`npm run validate -- data/atlas.json\` (add \`--json\` for machine-readable output). Fix every error and validate again. If you cannot run commands, check your output against the rules below before answering.
4. **Report** in two or three lines: what you created or changed, assumptions you made, and any warnings (for example a platform with no owner).

## Output format: the bundle

Output a single JSON object, and nothing else when the caller asks for raw output:

\`\`\`json
{ "atlas": 1, "entities": [ ... ], "relationships": [ ... ] }
\`\`\`

- Every entity has a \`kind\` and a stable \`id\`: lowercase letters, digits, dots, dashes or underscores, e.g. \`data-platform\`. Ids must be unique per kind.
- Every relationship is \`{ "from": "kind:id", "type": "<type>", "to": "kind:id" }\`, plus optional attributes for that type.
- Unknown fields are rejected. Put anything extra in a field starting with \`x-\`, or in \`meta\`.
- Exactly one \`organization\`.
- Other accepted names for kinds: ${aliases}. Prefer the canonical names.

## Entity kinds and fields

All kinds also accept \`description\`, \`tags\`, \`links\` (named URLs, e.g. \`{ "runbook": "https://..." }\`), \`order\` and \`meta\`.

${kindSections}

## Relationship types

Write relationships in the \`relationships\` list. The "Inline form" column is an alternative shorthand on the entity itself; in a bundle, prefer the explicit list.

${table(['Type', 'Category', 'From', 'To', 'Meaning', 'Inline form', 'Attributes', 'Also accepted'], relRows)}

These are **not** relationship entries; set them with entity fields:

${structural.map((t) => `- **${t.label}** (\`${t.id}\`): ${t.description}`).join('\n')}

## Allowed values

- Person \`tier\`: ${ids(vocab.tiers)}
- Person \`discipline\`: ${ids(vocab.disciplines)}
- Person \`employment\`: ${ids(vocab.employment)} (\`vacancy\` = open position, no \`name\`)
- Team \`type\`: ${ids(vocab.teamTypes)}
- Committee \`type\`: ${ids(vocab.committeeTypes)}
- Committee seat \`role\`: ${ids(vocab.seatRoles)}
- Platform and product \`hosting\`: ${schema.definitions.platform.properties.hosting.enum.map((x) => `\`${x}\``).join(', ')}
- \`criticality\`: ${schema.definitions.platform.properties.criticality.enum.map((x) => `\`${x}\``).join(', ')} (T0 is most critical)
- \`lifecycle\`: ${schema.definitions.platform.properties.lifecycle.enum.map((x) => `\`${x}\``).join(', ')}
- Product \`type\`: ${schema.definitions.product.properties.type.enum.map((x) => `\`${x}\``).join(', ')}

## Modeling rules

- **Shared ownership:** one \`owner\` relationship per owning team, each with a \`scope\` saying what that team owns ("Administration and runners" versus "Security policies").
- Every platform and product should have at least one \`owner\`. Leave it unowned only if the source says nobody owns it; it will be flagged.
- **Where a product runs** is \`deployed-to\` (with \`environments\` and \`regions\` lists). **What it uses** (a database, a queue, an identity provider) is \`uses\` with a \`purpose\`.
- People belong to teams through \`memberships\`. Someone on several teams has one \`{ "team": "...", "primary": true }\` and may have a per-team \`role\`.
- \`role\` on a person is free text in their own words; \`tier\` and \`discipline\` are the structured categories.
- Committees are not teams: give them a \`type\`, a \`chair\` and \`members\` with seat roles, and connect them with \`governs\`, \`advises\`, \`approver\` and \`reports-to\`.
- Team \`parent\` is a business unit id. Team and business unit \`lead\` is a person id.

## Logos

- \`si:<slug>\` for well-known products, from Simple Icons (https://simpleicons.org): for example \`si:snowflake\`, \`si:github\`, \`si:sonatype\` (Nexus), \`si:apachekafka\`, \`si:kubernetes\`, \`si:datadog\`, \`si:okta\`, \`si:databricks\`, \`si:mlflow\`, \`si:apacheairflow\`.
- Not in Simple Icons (use an Octicon instead): Salesforce, ServiceNow, Workday, AWS, Azure, SageMaker, dbt, Power BI, Tableau, Fivetran, Informatica.
- \`octicon:<name>\` for generic things (https://primer.style/octicons/): for example \`octicon:sync\`, \`octicon:database\`, \`octicon:browser\`, \`octicon:server\`.
- \`custom:<name>\` only when told a custom SVG exists in the icons folder.

## Complete example

\`\`\`json
${example}
\`\`\`
`;

  const tool = {
    name: 'submit_org_atlas_bundle',
    description:
      'Submit an Org Atlas data bundle: every entity (organization, business units, teams, people, platforms, products, committees) and every relationship between them. ' +
      GENERATED,
    input_schema: {
      type: 'object',
      properties: {
        atlas: { const: 1 },
        entities: { type: 'array', items: { $ref: '#/definitions/bundleEntity' } },
        relationships: { type: 'array', items: { $ref: '#/definitions/relationship' } },
      },
      required: ['atlas', 'entities', 'relationships'],
      additionalProperties: false,
      definitions: schema.definitions,
    },
  };

  const claudeAgent = `---
name: org-atlas-author
description: Creates or updates Org Atlas charts (org structure, teams, people, platforms, products, committees and their relationships) as validated JSON bundles. Use when asked to model an organization, add teams or people, record platform or product ownership, deployments, committees, or any relationship in Org Atlas.
tools: Read, Write, Edit, Bash, Glob, Grep
---

${body.replace('# Org Atlas authoring agent\n', '').trim()}

## In this repository

- Your data lives in \`data/\` (create it with \`npm run init\` if missing). Write bundles to \`data/atlas.json\`, or edit the existing YAML/JSON files there.
- Always run \`npm run validate\` after changing data, and fix errors before finishing.
- To see the current chart as one bundle: \`npm run export -- --out /tmp/current.json\`.
- Never edit \`engine/\`, \`site/\` or \`examples/\` unless asked to change the toolkit itself.
`;

  const agentsMd = `# AGENTS.md

<!-- ${GENERATED} -->

Instructions for coding agents (Codex, Cursor, Copilot, Claude Code and others) working in an Org Atlas repository.

## What this repository is

Org Atlas renders an organization (business units, teams, people, platforms, products, committees and their relationships) from data files into a static site for GitHub Pages.

- \`data/\`, \`atlas.config.yaml\`, \`overrides/\`: **user data**. This is what you normally edit.
- \`engine/\`, \`site/\`, \`examples/\`, \`schema/\`, \`agent/\`: **toolkit**. Change only when asked to change the toolkit itself.

## Commands

- \`npm run validate\`: check all data (run after every data change)
- \`npm run validate -- <file> --json\`: check one file, machine-readable
- \`npm run export -- --out <file>\`: the whole dataset as one JSON bundle
- \`npm run dev\`: local preview
- \`npm run build\`: production build

## Authoring data

Follow [agent/org-atlas-agent.md](agent/org-atlas-agent.md). It lists every entity kind, field, allowed value and relationship type, and is regenerated from the vocabulary whenever the toolkit changes.

## Changing the toolkit

If you change \`engine/vocab/*.yaml\`, the schema logic, or the bundle example, run \`npm run generate\` and commit the regenerated \`schema/\`, \`agent/\`, \`.claude/agents/\` and \`AGENTS.md\`. CI fails if they are out of date.
`;

  return { body, tool, claudeAgent, agentsMd };
}
